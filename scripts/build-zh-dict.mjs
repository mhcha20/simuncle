// Builds client/src/lib/zhS2HK.dict.ts: the parts of OpenCC's Simplified -> Hong Kong Traditional
// dictionaries the site needs, without the 1 MB phrase list.
//
// Character mapping + HK variants are kept whole. From the phrase list only the entries whose
// result differs from plain character-by-character conversion are kept (about 10k of 49k),
// so the output matches the full converter for practical purposes at a fraction of the size.
//
// Dictionaries: OpenCC (Apache License 2.0), via the opencc-js package.
// Run after upgrading opencc-js:  node scripts/build-zh-dict.mjs
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const libDir = fileURLToPath(new URL("../node_modules/opencc-js/dist/esm-lib/", import.meta.url));
const load = async rel => (await import(pathToFileURL(join(libDir, rel)).href)).default;

const { ConverterFactory } = await import(pathToFileURL(join(libDir, "core.js")).href);
const STCharacters = await load("dict/STCharacters.js");
const STPhrases = await load("dict/STPhrases.js");
const HKVariants = await load("dict/HKVariants.js");

const byChar = ConverterFactory([STCharacters]);
const phrases = STPhrases.split("|").filter(entry => {
  const [from, to] = entry.split(" ");
  return byChar(from) !== to;
});

const out = `// Generated by scripts/build-zh-dict.mjs from OpenCC dictionaries (Apache License 2.0). Do not edit.
export const ST_PHRASES = ${JSON.stringify(phrases.join("|"))};
export const ST_CHARACTERS = ${JSON.stringify(STCharacters)};
export const HK_VARIANTS = ${JSON.stringify(HKVariants)};
`;
writeFileSync(new URL("../client/src/lib/zhS2HK.dict.ts", import.meta.url), out);
console.log(`phrases kept: ${phrases.length}, file size: ${Math.round(Buffer.byteLength(out) / 1024)} KB`);
